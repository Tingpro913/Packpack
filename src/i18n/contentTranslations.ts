// ============================================
// Helper function to get translated text
// ============================================

export function getTranslatedTemplateName(name: string, lang: string): string {
  if (lang !== 'zh') return name;
  return templateNameTranslations[name] || name;
}

export function getTranslatedTemplateDesc(desc: string, lang: string): string {
  if (lang !== 'zh') return desc;
  return templateDescTranslations[desc] || desc;
}

export function getTranslatedCategory(category: string, lang: string): string {
  if (lang !== 'zh') return category;
  return categoryTranslations[category] || category;
}

export function getTranslatedItemName(name: string, lang: string): string {
  if (lang !== 'zh') return name;
  return itemTranslations[name] || name;
}

export function getTranslatedTip<T extends { title: string; category: string; description: string; steps: { title: string; description: string }[] }>(tip: T, lang: string): T {
  if (lang !== 'zh') return tip;
  const translated = tipsTranslations[tip.title];
  if (!translated) return tip;
  
  return {
    ...tip,
    title: translated.title,
    description: translated.description,
    category: translated.category,
    steps: tip.steps.map((step, i) => ({
      ...step,
      title: translated.steps[i]?.title || step.title,
      description: translated.steps[i]?.description || step.description,
    })),
  };
}
